"""Export assets + risks as CSV packages for Eramba CE UI import."""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

from .ingest import load_findings_dir
from .risk_engine import score_findings

REPO_ROOT = Path(__file__).resolve().parents[1]

RISK_ROW_RE = re.compile(
    r"^\|\s*(RISK-\d+)\s*\|\s*(.+?)\s*\|\s*(AST-\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|$"
)


def parse_baseline_risks(path: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = RISK_ROW_RE.match(line.strip())
        if not m:
            continue
        rows.append(
            {
                "risk_id": m.group(1),
                "title": m.group(2).strip(),
                "asset_id": m.group(3),
                "likelihood": m.group(4),
                "impact": m.group(5),
                "score": m.group(6),
                "treatment": m.group(7).strip(),
                "owner": m.group(8).strip(),
                "status": m.group(9).strip(),
            }
        )
    return rows


def write_assets_csv(src: Path, dest: Path) -> int:
    with src.open(encoding="utf-8", newline="") as f_in, dest.open(
        "w", encoding="utf-8", newline=""
    ) as f_out:
        reader = csv.DictReader(f_in)
        fieldnames = [
            "Asset ID",
            "Name",
            "Description",
            "Classification",
            "Owner",
            "IP/Location",
            "Category",
        ]
        writer = csv.DictWriter(f_out, fieldnames=fieldnames)
        writer.writeheader()
        n = 0
        for row in reader:
            writer.writerow(
                {
                    "Asset ID": row["asset_id"],
                    "Name": row["hostname_or_name"],
                    "Description": row.get("notes", ""),
                    "Classification": row["classification"],
                    "Owner": row["owner"],
                    "IP/Location": row["ip_or_location"],
                    "Category": row["category"],
                }
            )
            n += 1
    return n


def write_risks_csv(
    baseline: list[dict[str, str]],
    scored_findings: list[dict],
    dest: Path,
) -> int:
    fieldnames = [
        "Risk ID",
        "Title",
        "Asset ID",
        "Likelihood",
        "Impact",
        "Score",
        "Treatment",
        "Owner",
        "Status",
        "Source Finding",
        "Evidence",
    ]
    with dest.open("w", encoding="utf-8", newline="") as f_out:
        writer = csv.DictWriter(f_out, fieldnames=fieldnames)
        writer.writeheader()
        for r in baseline:
            writer.writerow(
                {
                    "Risk ID": r["risk_id"],
                    "Title": r["title"],
                    "Asset ID": r["asset_id"],
                    "Likelihood": r["likelihood"],
                    "Impact": r["impact"],
                    "Score": r["score"],
                    "Treatment": r["treatment"],
                    "Owner": r["owner"],
                    "Status": r["status"],
                    "Source Finding": "",
                    "Evidence": "docs/risk-register-baseline.md",
                }
            )
        for s in scored_findings:
            writer.writerow(
                {
                    "Risk ID": s.get("related_risk_id") or s["finding_id"],
                    "Title": s["title"],
                    "Asset ID": s["asset_id"],
                    "Likelihood": s["likelihood"],
                    "Impact": s["impact"],
                    "Score": s["score"],
                    "Treatment": s["treatment"],
                    "Owner": "",
                    "Status": "From sample finding",
                    "Source Finding": s["finding_id"],
                    "Evidence": s.get("evidence", ""),
                }
            )
    return len(baseline) + len(scored_findings)


def write_import_md(out_dir: Path, asset_n: int, risk_n: int) -> None:
    text = f"""# Eramba CE import checklist

Generated by `python -m src.eramba_export`.

## Files

| File | Rows |
|------|------|
| `assets.csv` | {asset_n} |
| `risks.csv` | {risk_n} |

## Click path (Community Edition)

1. Log into Eramba CE web UI.
2. **Assets** → Import (or bulk create) using `assets.csv`. Map columns to your CE field names if prompted.
3. **Risks** (Security Risks / Risk Management — label varies by version) → Import `risks.csv`.
4. Manually link top risks to controls from `docs/control-register.md` if import cannot set relations.
5. Screenshot the risk register → save as `docs/img/eramba-risk-register.png`.
6. Link the screenshot from README (completes **R2-S2.3**).

## Notes

- Exact import menus differ by Eramba version — adjust column mapping in the UI wizard.
- REST API is **Enterprise-only**; CE users stay on this CSV path.
- See `docs/eramba-notes.md` for edition details and env template.
"""
    (out_dir / "IMPORT.md").write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export CSV package for Eramba CE import")
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "artifacts" / "eramba-import",
    )
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)

    asset_n = write_assets_csv(
        REPO_ROOT / "config" / "asset-inventory.csv",
        args.out / "assets.csv",
    )
    baseline = parse_baseline_risks(REPO_ROOT / "docs" / "risk-register-baseline.md")
    findings = load_findings_dir(REPO_ROOT / "samples" / "findings")
    scored = [s.to_dict() for s in score_findings(findings)]
    risk_n = write_risks_csv(baseline, scored, args.out / "risks.csv")
    write_import_md(args.out, asset_n, risk_n)
    print(f"Wrote {args.out} (assets={asset_n}, risks={risk_n})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
